"""
CI/CD Validator Agent — Lab 11: Agentic SDLC Factory.

Simulates a CI/CD pipeline for a given CodeArtifact and set of TestCases.
No real build tools, containers, or deployment infrastructure are used;
all stages are deterministic simulations.

Stages:
1. **CI Build** — validate artifact structure and compile constraints.
2. **CI Test**  — tally TestCase results.
3. **CD Deploy** — deploy to staging (always) or production (if quality gate
   passed).
"""
from __future__ import annotations

import logging
import time
from typing import Any

from models.schemas import (
    CICDReport,
    CodeArtifact,
    QualityGateReport,
    QualityGateStatus,
    TestCase,
    TestStatus,
)

logger = logging.getLogger(__name__)

# Simulated build/deploy timing constants (ms)
_BASE_BUILD_MS = 850.0
_MS_PER_LINE = 0.5
_BASE_DEPLOY_MS = 400.0


class CICDValidator:
    """Agent that simulates a CI/CD pipeline for a given story's artifacts.

    CI Build Phase
    --------------
    * Checks ``code_lines > 0`` — fails if the artifact is empty.
    * Checks ``complexity_score <= max_complexity`` — fails if too complex.
    * Simulates build time proportional to code lines.

    CI Test Phase
    -------------
    * Tallies ``pass / fail / skipped`` counts from the provided test cases.
    * Build must succeed for tests to run.

    CD Deploy Phase
    ---------------
    * Deploys to ``staging`` if build succeeded.
    * Deploys to ``production`` only if the quality gate report is provided
      and its status is ``PASSED``.
    * Simulates deploy time.
    """

    def __init__(self, config: dict[str, Any] | None = None) -> None:
        """Initialise the CICDValidator.

        Args:
            config: Optional configuration dictionary.  Keys:

                * ``max_complexity`` (int): Maximum allowed complexity for build
                  to pass.  Defaults to ``7``.
                * ``deploy_target_staging`` (str): Hostname for staging.
                * ``deploy_target_prod`` (str): Hostname for production.
        """
        self.config: dict[str, Any] = config or {}
        self._max_complexity: int = int(
            self.config.get("max_complexity", 7)
        )
        self._staging: str = str(
            self.config.get(
                "deploy_target_staging", "staging.faculty-appraisal.local"
            )
        )
        self._prod: str = str(
            self.config.get(
                "deploy_target_prod", "prod.faculty-appraisal.local"
            )
        )
        logger.debug(
            "CICDValidator initialised (max_complexity=%d, staging=%s, prod=%s)",
            self._max_complexity,
            self._staging,
            self._prod,
        )

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def validate(
        self,
        artifact: CodeArtifact,
        test_cases: list[TestCase],
        quality_gate: QualityGateReport | None = None,
    ) -> CICDReport:
        """Run the full CI/CD pipeline simulation.

        Args:
            artifact: The code artifact produced by the generation stage.
            test_cases: Test cases generated by the TDD generator.
            quality_gate: Optional quality gate report; if provided and
                ``status == PASSED``, the artifact is deployed to production.

        Returns:
            A :class:`~models.schemas.CICDReport` summarising every phase.
        """
        logger.info(
            "Starting CI/CD pipeline for artifact %s (story=%s)",
            artifact.artifact_id,
            artifact.story_id,
        )

        # -- CI Build ------------------------------------------------------
        build_success, build_ms = self._run_build(artifact)

        # -- CI Test -------------------------------------------------------
        passed, failed, skipped = self._run_tests(test_cases, build_success)

        # -- CD Deploy -----------------------------------------------------
        gate_passed = (
            quality_gate is not None
            and quality_gate.status == QualityGateStatus.PASSED
        )
        deploy_target, deploy_success, deploy_ms = self._run_deploy(
            artifact, build_success, failed, gate_passed
        )

        report = CICDReport(
            story_id=artifact.story_id,
            build_success=build_success,
            build_duration_ms=build_ms,
            test_results=test_cases,
            tests_passed=passed,
            tests_failed=failed,
            tests_skipped=skipped,
            deploy_target=deploy_target,
            deploy_success=deploy_success,
            deploy_duration_ms=deploy_ms,
        )

        logger.info(
            "CI/CD complete for %s: build=%s, tests=%d/%d passed, deploy=%s→%s",
            artifact.story_id,
            "✓" if build_success else "✗",
            passed,
            passed + failed,
            "✓" if deploy_success else "✗",
            deploy_target,
        )
        return report

    # ------------------------------------------------------------------
    # Private stage runners
    # ------------------------------------------------------------------

    def _run_build(self, artifact: CodeArtifact) -> tuple[bool, float]:
        """Simulate the CI build phase.

        Args:
            artifact: Artifact to build.

        Returns:
            A ``(success, duration_ms)`` tuple.
        """
        logger.debug("CI Build: validating artifact %s …", artifact.artifact_id)
        success = True
        reason = "ok"

        if artifact.code_lines == 0:
            success = False
            reason = "empty artifact"
        elif artifact.complexity_score > self._max_complexity:
            success = False
            reason = (
                f"complexity {artifact.complexity_score} > {self._max_complexity}"
            )

        duration_ms = _BASE_BUILD_MS + artifact.code_lines * _MS_PER_LINE

        if success:
            logger.debug("CI Build PASSED in %.0f ms.", duration_ms)
        else:
            logger.warning("CI Build FAILED (%s) in %.0f ms.", reason, duration_ms)

        return success, duration_ms

    @staticmethod
    def _run_tests(
        test_cases: list[TestCase], build_success: bool
    ) -> tuple[int, int, int]:
        """Tally test results.

        If the build failed, all tests are counted as skipped.

        Args:
            test_cases: List of test cases with pre-set statuses.
            build_success: Whether the build phase succeeded.

        Returns:
            A ``(passed, failed, skipped)`` tuple.
        """
        if not build_success:
            logger.warning(
                "Skipping all %d tests because build failed.", len(test_cases)
            )
            return 0, 0, len(test_cases)

        passed = sum(1 for tc in test_cases if tc.status == TestStatus.PASS)
        failed = sum(1 for tc in test_cases if tc.status == TestStatus.FAIL)
        skipped = sum(1 for tc in test_cases if tc.status == TestStatus.SKIPPED)

        logger.debug(
            "CI Tests: %d passed, %d failed, %d skipped.", passed, failed, skipped
        )
        return passed, failed, skipped

    def _run_deploy(
        self,
        artifact: CodeArtifact,
        build_success: bool,
        failed_tests: int,
        gate_passed: bool,
    ) -> tuple[str, bool, float]:
        """Simulate the CD deploy phase.

        Args:
            artifact: The artifact to deploy.
            build_success: Whether the build succeeded.
            failed_tests: Number of failing tests.
            gate_passed: Whether the quality gate passed.

        Returns:
            A ``(deploy_target, deploy_success, duration_ms)`` tuple.
        """
        deploy_ms = _BASE_DEPLOY_MS

        if not build_success:
            logger.warning(
                "Deploy skipped for %s: build failed.", artifact.story_id
            )
            return "none", False, 0.0

        # Always try staging first
        if gate_passed and failed_tests == 0:
            target = self._prod
            logger.debug(
                "Quality gate passed — deploying %s to production: %s",
                artifact.story_id,
                target,
            )
        else:
            target = self._staging
            logger.debug(
                "Deploying %s to staging: %s (gate_passed=%s, failed_tests=%d)",
                artifact.story_id,
                target,
                gate_passed,
                failed_tests,
            )

        deploy_success = True  # simulation always succeeds once build passes
        logger.info(
            "Deploy %s → %s: %s (%.0f ms)",
            artifact.story_id,
            target,
            "SUCCESS" if deploy_success else "FAILED",
            deploy_ms,
        )
        return target, deploy_success, deploy_ms
